export function translate(
  locale: Locale,
  key: TranslationKey,
  variables: Record<string, string | number> = {},
): string {
  const template = locale === "zh" ? zh[key] : en[key];
  return Object.entries(variables).reduce(
    (value, [name, replacement]) => value.split(`{${name}}`).join(String(replacement)),
    template,
  );
}

export function translateKnownText(locale: Locale, value: string): string {
  return knownText[locale][value] ?? value;
}

export function translateStatus(locale: Locale, value: string): string {
  const key = `status.${value}` as TranslationKey;
  return key in en ? translate(locale, key) : translateKnownText(locale, value);
}

export function translateMode(locale: Locale, value: string): string {
  const key = `mode.${value}` as TranslationKey;
  return key in en ? translate(locale, key) : value;
}

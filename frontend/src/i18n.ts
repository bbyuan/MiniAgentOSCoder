export function translate(
  locale: Locale,
  key: TranslationKey,
  variables: Record<string, string | number> = {},
): string {
  const template = locale === "zh" ? zh[key] : en[key];
  return Object.entries(variables).reduce(
    (value, [name, replacement]) => value.split(`{${name}}`).join(String(replacement)),
    template,
  );
}

export function translateKnownText(locale: Locale, value: string): string {
  const exact = knownText[locale][value];
  if (exact || locale !== "zh") return exact ?? value;
  if (value.startsWith("available ") && value.endsWith(" memory")) {
    const scope = value.slice("available ".length, -" memory".length);
    return `可用的${scope === "long_term" ? "长期" : scope === "project" ? "项目" : scope}记忆`;
  }
  if (value.startsWith("Tool requires approval before execution: ")) {
    return `工具执行前需要审批：${translateKnownText(locale, value.slice(41))}`;
  }
  if (value.startsWith("Tool uses ") && value.endsWith(" boundary")) {
    return `工具使用 ${value.slice(10, -9)} 边界`;
  }
  if (value.startsWith("Command is accepted by the ") && value.endsWith(" sandbox profile")) {
    return `命令已通过${translateKnownText(locale, value.slice(27, -16))}沙箱配置检查`;
  }
  return value;
}

export function translateExtensionDiagnostic(locale: Locale, value: string): string {
  if (locale !== "zh") return value;
  const exact: Record<string, string> = {
    "MCP server entry must be a mapping": "外部工具服务条目必须是映射对象",
    "Hook entry must be a mapping": "自动检查条目必须是映射对象",
  };
  if (exact[value]) return exact[value];
  const prefixes: Array<[string, string]> = [
    ["Skills registry: ", "项目规则目录："],
    ["MCP registry: ", "外部工具目录："],
    ["Hook registry: ", "自动检查目录："],
  ];
  const matched = prefixes.find(([prefix]) => value.startsWith(prefix));
  return matched ? `${matched[1]}${value.slice(matched[0].length)}` : value;
}

export function localizeErrorMessage(locale: Locale, caught: unknown, fallback: string): string {
  const message = caught instanceof Error ? caught.message.trim() : "";
  if (!message) return fallback;
  if (locale !== "zh") return message;
  if (/failed to fetch|load failed|networkerror|network request failed/i.test(message)) {
    return "本地后端服务未连接。请先启动后端服务，然后刷新当前页面。";
  }
  if (/timeout|timed out/i.test(message)) {
    return "请求超时，请稍后重试。";
  }
  const incompatibleSkill = message.match(/^Skill (.+) is not compatible with mode (.+)$/);
  if (incompatibleSkill) {
    return `“${incompatibleSkill[1]}”不适合“${translateMode(locale, incompatibleSkill[2])}”任务。请关闭这条项目规则，或切换到适合的任务类型。`;
  }
  return translateKnownText(locale, message);
}

export function translateStatus(locale: Locale, value: string): string {
  const key = `status.${value}` as TranslationKey;
  return key in en ? translate(locale, key) : translateKnownText(locale, value);
}

export function translateMode(locale: Locale, value: string): string {
  const directKey = `mode.${value}` as TranslationKey;
  if (directKey in en) return translate(locale, directKey);
  const normalized = value.toLowerCase();
  const matchedKey = Object.keys(en).find((key) => key.toLowerCase() === `mode.${normalized}`) as TranslationKey | undefined;
  return matchedKey ? translate(locale, matchedKey) : value;
}
